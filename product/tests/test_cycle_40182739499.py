#: Root scratch names that 40170987954 committed and this cycle retired.
FORBIDDEN_ROOT = (
    "check_bundle.py", "check_bundle2.py", "server.log",
    "test_query_flow.py", "test_query_run.py",
)


def _load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def _git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=str(REPO_ROOT),
                          capture_output=True, text=True)


def _sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


# ---------------------------------------------------------------------------
# 2. Validation repair: byte-exact retirement + tip-tree scope ratchet
# ---------------------------------------------------------------------------

def test_every_retired_file_is_byte_exact_per_its_manifest_entry() -> None:
    man = _load(MANIFEST)
    assert man["repaired_by_run"] == RUN_ID
    assert man["retired_files"], "manifest must inventory the retired bytes"
    for entry in man["retired_files"]:
        path = REPO_ROOT / entry["retired_path"]
        assert path.exists(), f"retired file missing: {entry['retired_path']}"
        assert _sha256(path) == entry["sha256"], (
            f"retired bytes changed for {entry['retired_path']} - retirement "
            "must be byte-exact, never a rewrite")
    # the manifest must cover every file actually present in the incident dir
    on_disk = {p.relative_to(REPO_ROOT).as_posix()
               for p in INCIDENT_DIR.iterdir() if p.name != "MANIFEST.json"}
    in_manifest = {e["retired_path"] for e in man["retired_files"]}
    assert on_disk == in_manifest, (on_disk ^ in_manifest)


def test_the_root_scratch_names_are_gone_and_the_clobbered_test_is_restored() -> None:
    for name in FORBIDDEN_ROOT:
        assert not (REPO_ROOT / name).exists(), (
            f"out-of-scope root scratch {name} reappeared at the tip")
    man = _load(MANIFEST)
    blob = _git("hash-object", "test_server.py").stdout.strip()
    assert blob == man["restoration"]["blob_sha1"], (
        "root test_server.py no longer matches the restored accepted blob")
    # when the accepted-branch ref is available, cross-check it directly
    ref = _git("rev-parse", "--verify", "--quiet",
               "origin/lab/product:test_server.py")
    if ref.returncode == 0:
        assert blob == ref.stdout.strip(), (
            "root test_server.py diverged from origin/lab/product")
    # the clobbered scratch content is preserved in retirement, not lost
    clobbered = INCIDENT_DIR / "test_server.clobbered_40170987954.py.RETIRED"
    assert clobbered.exists()
    clob_blob = _git("hash-object", str(clobbered)).stdout.strip()
    f4 = _git("rev-parse", "--verify", "--quiet", "f4d6e3b:test_server.py")
    if f4.returncode == 0:
        assert clob_blob == f4.stdout.strip(), (
            "retired clobbered copy must stay byte-identical to f4d6e3b")


