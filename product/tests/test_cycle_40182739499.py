INCIDENT_DIR = (REPO_ROOT / "reports" / "product" / "incidents"
                / "out_of_scope_40170987954_scratch")
MANIFEST = INCIDENT_DIR / "MANIFEST.json"
PROBE_ART = (REPO_ROOT / "results" / "product" / "counter_content_family"
             / f"CYCLE_{RUN_ID}.json")
