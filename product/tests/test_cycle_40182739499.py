def test_latest_content_family_instrument_reproduces_and_covers_the_new_bundles() -> None:
    art = _load(PROBE_ART)
    assert art["run_id"] == RUN_ID
    fresh = cfp.run(run_id=RUN_ID, direction_version=DIRV)
    for key in ("fixed_path_family", "all_committed", "false_reject_count",
                "ordered_work_2_success_rule", "confirmed_set",
                "family_definition", "claim_ceiling"):
        assert fresh[key] == art[key], key

    totals = art["fixed_path_family"]["totals"]
    hist = totals["defect_histogram"]
    assert hist == {"D1_empty_evidence": 0, "D2_letterhead_zone": 0,
                    "D3_markup_residue": 0, "D4_language_marker_mismatch": 0}
    assert totals["n_verified_defective"] == 0
    assert art["false_reject_count"] == 0
    assert art["ordered_work_2_success_rule"]["met"] is True
    assert art["confirmed_set"]["still_verified"] is True

    # non-vacuous and grown past the previous instrument (25 -> >= 29)
    assert totals["n_bundles"] >= 29
    assert totals["n_verified"] >= 12
    covered = {b["path"] for b in art["fixed_path_family"]["bundles"]}
    assert set(NEW_FLAGSHIP) <= covered, (
        "the bundles regenerated by cycle 40170987954 must be covered by the "
        "latest instrument")
    # historical defects stay preserved beside the fixed path
    history = art["all_committed"]["totals"]["defect_histogram"]
    assert history["D2_letterhead_zone"] > 0


