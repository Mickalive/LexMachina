"""Executable re-derivation of product cycle 40182739499's published claims.

This cycle is the OPERATIONAL RESUME of run 40181378979 (dispatched by the
resilience job after that run concluded failure with zero durable delta), so
the claims fall into four groups that are never mixed:

1. **Orchestration diagnosis** - runs 40173935166 and 40181378979 both ended
   with team snapshot refs pointing at their predecessor's commit (zero files
   changed).  Re-derived from LOCAL refs by ``product/zero_delta_chain_diagnosis.py``.
   From refs alone rc-67 LEX_ZERO_DELTA_REPAIR and a producer death are
   indistinguishable; both are orchestration outcomes, NOT product defects and
   NOT verdicts (factory-wide requirements 10 and 20).  No network, no token.
2. **Validation repair** - run 40170987954 had committed five producer-scratch
   files at the repository root and clobbered the pre-existing legacy root
   ``test_server.py``; all six bytes are retired BYTE-EXACTLY into
   ``reports/product/incidents/out_of_scope_40170987954_scratch/`` and the
   root file is restored from ``origin/lab/product``.  The scope guard only
   inspects pending changes, so committed out-of-scope bytes are invisible to
   it - the same class that let producer-minted audit gates reach the chain in
   run 40163751502 (reports/product/CYCLE_40168184617.md section 2).
3. **Measurement** - the frozen D2/D3/D4 content-family probe re-run covers the
   four flagship bundles that 40170987954 regenerated AFTER the previous
   instrument (29 fixed-path bundles now, still D2=D3=D4=D1=0, 0 false
   rejects, the sound row ``bstger_SK.2023.49`` still verified), and the
   shipped progressive query-slice smoke proves the vertical slice still
   answers over a real socket.
4. **Posture** - the accepted pointer still satisfies BOTH halves of
   factory-wide requirement 4, every fail-closed flag stays FALSE, and the
   chain runs remain UNADJUDICATED.

Nothing here writes a gate, scores a frozen bar, or labels a chain run
"rejected".
"""
from __future__ import annotations

