"""Machine-readable packet admission input: the two accepted frozen bars.

Factory direction v50, product obligation (1): make the two accepted bar
verdicts a MACHINE-READABLE INPUT of packet admission, so no packet, owner
card, disclosure or state field can carry ``ready_for_owner_session=true`` or
``human_gate_ready=true`` while either accepted bar is unmet.

The two bars and their verdicts are ACCEPTED EVIDENCE, not product opinions:

* counter-label support — frozen rubric ``RULES_LABEL.json`` sha256
  4457e971df3dc5d10af2a727aa675afc15a15564c18eed4cede0af5eb41b4608,
  absolute bar 1.0; measured 5/65 = 0.076923 (LABEL_UNSOUND) on packet
  38839347028 by frontier-served-packet-falsification run 38880639079
  (audit gate=PASS, accept commit 464c45f7).
* map-geometry minimum semantics — frozen rule sha256
  a7452748d40c511a14a1c7848ece5fe7f8f8901cc30f45a66918c89eb593a633,
  bar = all 11 criteria on every served bundle; measured 0/3 with the French
  largest cluster at 0.7696 against the 0.60 STRUCTURE_LARGEST bar.

Source of record: the product-owned accepted snapshot
``results/product/frontier_verdicts/ACCEPTED_frontier-served-packet-
falsification_38880639079.json`` (harvested from the accepted Frontier
verdict; the frozen packet itself is never regenerated by this module).

This module READS and ENFORCES.  It never re-measures a bar (re-measuring
labels or geometry is Core Evaluation's / Frontier's job), never edits a
threshold, and never sets ``human_gate_ready`` — it only refuses to let a
packet admission claim readiness while a bar is unmet.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
SNAPSHOT_PATH = (
    REPO_ROOT / "results" / "product" / "frontier_verdicts" /
    "ACCEPTED_frontier-served-packet-falsification_38880639079.json"
)
DEFAULT_OUT = REPO_ROOT / "results" / "product" / "bar_admission" / "ACCEPTED_BARS.json"

LABEL_RULES_SHA256 = "4457e971df3dc5d10af2a727aa675afc15a15564c18eed4cede0af5eb41b4608"
GEOMETRY_RULES_SHA256 = "a7452748d40c511a14a1c7848ece5fe7f8f8901cc30f45a66918c89eb593a633"

SCHEMA = "product-bar-admission/1"

CLAIM_CEILING = (
    "these are the two ACCEPTED frozen-bar verdicts consumed as packet-admission "
    "input. This module never re-measures a bar, never edits a threshold and never "
    "sets human_gate_ready; while either bar is unmet, no packet may claim "
    "ready_for_owner_session=true."
)


class BarSourceError(RuntimeError):
    """The accepted snapshot is missing, unreadable or not the accepted bytes."""


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_snapshot(path: Path = SNAPSHOT_PATH) -> dict[str, Any]:
    if not path.is_file():
        raise BarSourceError(f"accepted frontier verdict snapshot missing: {path}")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise BarSourceError(f"accepted snapshot unreadable: {exc}") from exc
    if data.get("team_run_id") != "38880639079" or data.get("status") != "PROMOTED":
        raise BarSourceError(
            "snapshot is not the accepted served-packet-falsification verdict "
            f"(team_run_id={data.get('team_run_id')!r}, status={data.get('status')!r})"
        )
    return data


def accepted_bars(path: Path = SNAPSHOT_PATH) -> dict[str, Any]:
    """Return the two accepted bars as one machine-readable admission record."""
    snap = _load_snapshot(path)
    label = snap.get("label_half") or {}
    geometry = snap.get("geometry_half") or {}

    for name, sha, block in (
        ("counter_label_support", LABEL_RULES_SHA256, label),
        ("map_geometry_semantics", GEOMETRY_RULES_SHA256, geometry),
    ):
        claim = str(block.get("claim_text") or "")
        if sha not in claim:
            raise BarSourceError(
                f"{name}: frozen rules sha {sha} absent from the accepted claim_text; "
                "refusing to admit a bar whose frozen rule cannot be identified"
            )

    n_scored = int(label.get("n_scored") or 0)
    n_supported = int(label.get("n_supported") or 0)
    label_met = bool(n_scored > 0 and n_supported == n_scored)

    n_bundles = int(geometry.get("n_bundles") or 0)
    n_pass = int(geometry.get("n_bundles_pass") or 0)
    geometry_met = bool(n_bundles > 0 and n_pass == n_bundles)

    bars = {
        "counter_label_support": {
            "rules_sha256": LABEL_RULES_SHA256,
            "bar": "absolute: every scored counter label is supported by its own cited evidence (1.0)",
            "measured_support_rate": label.get("support_rate"),
            "n_scored": n_scored,
            "n_supported": n_supported,
            "verdict": label.get("verdict"),
            "met": label_met,
            "measured_by": "frontier-served-packet-falsification run 38880639079 (accepted)",
            "measured_population": snap.get("measured_packet"),
        },
        "map_geometry_semantics": {
            "rules_sha256": GEOMETRY_RULES_SHA256,
            "bar": "all 11 frozen minimum-semantics criteria pass on every served bundle",
            "n_bundles_pass": n_pass,
            "n_bundles": n_bundles,
            "pass_counts": geometry.get("pass_counts"),
            "baseline_pass_counts": geometry.get("baseline_pass_counts"),
            "french_largest_share": geometry.get("french_largest_share"),
            "french_bar": geometry.get("french_bar"),
            "verdict": geometry.get("verdict"),
            "met": geometry_met,
            "measured_by": "frontier-served-packet-falsification run 38880639079 (accepted)",
            "measured_population": snap.get("measured_packet"),
        },
    }
    unmet = [k for k, v in bars.items() if not v["met"]]
    return {
        "schema": SCHEMA,
        "direction_version": 50,
        "obligation": "factory direction v50 product obligation (1): machine-readable bar input of packet admission",
        "source_snapshot": {
            "path": str(path.relative_to(REPO_ROOT)) if path.is_relative_to(REPO_ROOT) else str(path),
            "sha256": _sha256_file(path),
            "team_run_id": snap.get("team_run_id"),
            "accept_commit": snap.get("accept_commit"),
            "covers_this_packet": snap.get("covers_this_packet"),
        },
        "bars": bars,
        "all_bars_met": not unmet,
        "unmet_bars": unmet,
        "serve_recommendation": snap.get("serve_recommendation"),
        "claim_ceiling": CLAIM_CEILING,
    }


def enforce_packet_admission(summary: dict[str, Any], *, path: Path = SNAPSHOT_PATH) -> dict[str, Any]:
    """Gate ``ready_for_owner_session`` on both accepted bars.

    Returns the SAME summary object with ``accepted_bars`` attached and
    ``ready_for_owner_session`` forced to ``False`` when either bar is unmet.
    The reason is recorded on the summary so a reader never has to guess.
    """
    bars = accepted_bars(path)
    summary["accepted_bars"] = bars
    if bars["all_bars_met"]:
        return summary
    was_ready = bool(summary.get("ready_for_owner_session"))
    summary["ready_for_owner_session"] = False
    summary["ready_for_owner_session_blocked_by_bars"] = {
        "unmet_bars": list(bars["unmet_bars"]),
        "would_have_been_ready": was_ready,
        "serve_recommendation": bars.get("serve_recommendation"),
        "note": CLAIM_CEILING,
    }
    return summary


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args(argv)
    bars = accepted_bars()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(bars, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
                   encoding="utf-8")
    print(json.dumps({
        "wrote": str(out),
        "all_bars_met": bars["all_bars_met"],
        "unmet_bars": bars["unmet_bars"],
    }, indent=2))
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
